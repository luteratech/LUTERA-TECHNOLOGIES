const business = (
  id: string,
  department: string,
  label: string,
  description: string,
  area: Area,
  module: string,
  kind?: string,
  create?: string,
): WorkspaceTool => ({
  id,
  department,
  label,
  description,
  area,
  section: "operations",
  params: { module, ...(kind ? { kind } : {}) },
  create,
});
