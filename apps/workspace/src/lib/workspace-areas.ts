export function visibleTools(role: Role, config: WorkspaceAccess | null) {
  return workspaceTools.filter(
    (t) =>
      (!t.ownerOnly || !!config?.owner) &&
      (!t.capability || can(role, t.capability)) &&
      (!t.area ||
        !!config?.access[t.area]?.read ||
        (t.id === "tasks" && !!config?.access.support?.read)) &&
      (!t.also || !!config?.access[t.also]?.read),
  );
}
export function toolAt(
  section: string,
  params: URLSearchParams,
  tools: WorkspaceTool[] = workspaceTools,
) {
  const matches = tools.filter(
    (t) =>
      t.section === section &&
      Object.entries(t.params || {}).every(([k, v]) => params.get(k) === v),
  );
  return matches.find((t) => t.id === params.get("tool")) || matches[0];
}
